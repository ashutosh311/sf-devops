#!/usr/bin/env node
/**
 * Stamps a release version into every package.json and regenerates
 * packages/core/src/version.ts (`TOOL_VERSION`).
 *
 * This is a release-workflow implementation detail, not a developer command.
 * The single source of truth for a release version is the git tag that
 * triggers `.github/workflows/release.yml` — that workflow calls this script
 * with `--version` derived from the tag. The changes it makes are never
 * committed; they only exist in the CI working tree for that build.
 *
 * Local builds don't need a real version — the placeholder ("0.0.0") checked
 * into each package.json is fine for `pnpm build` / `pnpm typecheck`.
 *
 * Usage:
 *   node scripts/sync-version.mjs --version <semver>
 */

import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const WORKSPACE_ROOT = resolve(__dirname, "..");

// ── Parse CLI args ────────────────────────────────────────────────────────────

const args = process.argv.slice(2);
const versionIdx = args.indexOf("--version");
const version = versionIdx !== -1 ? args[versionIdx + 1] : undefined;

if (!version) {
  console.error("Usage: node scripts/sync-version.mjs --version <semver>");
  process.exit(1);
}

// ── Write version into each package.json ──────────────────────────────────────

const PACKAGES = ["core", "mcp", "vscode", "cli"];

for (const pkg of PACKAGES) {
  const pkgPath = join(WORKSPACE_ROOT, "packages", pkg, "package.json");
  const pkgJson = JSON.parse(readFileSync(pkgPath, "utf-8"));
  pkgJson.version = version;
  writeFileSync(pkgPath, JSON.stringify(pkgJson, null, 2) + "\n", "utf-8");
  console.log(`  ✓ packages/${pkg}/package.json → ${version}`);
}

// ── Regenerate packages/core/src/version.ts ───────────────────────────────────

const versionTsPath = join(WORKSPACE_ROOT, "packages", "core", "src", "version.ts");
const versionTs = `// AUTO-GENERATED by scripts/sync-version.mjs during the release workflow — do not edit or commit.
// The single source of truth for a release version is the git tag on Slalom/salesforce-devops.
export const TOOL_VERSION = "${version}";
`;
writeFileSync(versionTsPath, versionTs, "utf-8");
console.log(`  ✓ packages/core/src/version.ts → TOOL_VERSION = ${version}`);

console.log(`\nTool version stamped as ${version}.`);
